public class RescueAnimal {

    // Instance variables
    private String name;
    private String animalType;
    private String gender;
    private String age;
    private String weight;
    private String acquisitionDate;
    private String acquisitionLocation;
    private String trainingStatus;
    private boolean reserved;
    private String inServiceCountry;

    // Default constructor
    public RescueAnimal() {
    }

    // Get name
    public String getName() {
        return name;
    }

    // Set name
    public void setName(String name) {
        this.name = name;
    }

    // Get animal type
    public String getAnimalType() {
        return animalType;
    }

    // Set animal type
    public void setAnimalType(String animalType) {
        this.animalType = animalType;
    }

    // Get gender
    public String getGender() {
        return gender;
    }

    // Set gender
    public void setGender(String gender) {
        this.gender = gender;
    }

    // Get age
    public String getAge() {
        return age;
    }

    // Set age
    public void setAge(String age) {
        this.age = age;
    }

    // Get weight
    public String getWeight() {
        return weight;
    }

    // Set weight
    public void setWeight(String weight) {
        this.weight = weight;
    }

    // Get acquisition date
    public String getAcquisitionDate() {
        return acquisitionDate;
    }

    // Set acquisition date
    public void setAcquisitionDate(String acquisitionDate) {
        this.acquisitionDate = acquisitionDate;
    }

    // Get acquisition location
    public String getAcquisitionLocation() {
        return acquisitionLocation;
    }

    // Set acquisition location
    public void setAcquisitionLocation(String acquisitionLocation) {
        this.acquisitionLocation = acquisitionLocation;
    }

    // Get training status
    public String getTrainingStatus() {
        return trainingStatus;
    }

    // Set training status
    public void setTrainingStatus(String trainingStatus) {
        this.trainingStatus = trainingStatus;
    }

    // Get reserved
    public boolean getReserved() {
        return reserved;
    }

    // Set reserved
    public void setReserved(boolean reserved) {
        this.reserved = reserved;
    }

    // Get in-service country
    public String getInServiceCountry() {
        return inServiceCountry;
    }

    // Set in-service country
    public void setInServiceCountry(String inServiceCountry) {
        this.inServiceCountry = inServiceCountry;
    }
}